export function ReportMarkdown({ markdown }: { markdown: string }) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n')
  const blocks: ReactNode[] = []
  let bullets: string[] = []
  let key = 0

  function flushBullets() {
    if (bullets.length === 0) return
    const items = bullets
    bullets = []
    blocks.push(
      <ul key={key++} className="mb-4 list-disc space-y-1 pl-5">
        {items.map((item) => (
          <li key={key++}>{inline(item)}</li>
        ))}
      </ul>,
    )
  }

  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed) {
      flushBullets()
      continue
    }
    if (trimmed.startsWith('- ')) {
      bullets.push(trimmed.slice(2))
      continue
    }
    flushBullets()
    if (trimmed.startsWith('### ')) {
      blocks.push(
        <h3 key={key++} className="mb-2 mt-5 text-[18px] font-medium leading-6">
          {inline(trimmed.slice(4))}
        </h3>,
      )
    } else if (trimmed.startsWith('# ')) {
      blocks.push(
        <h2 key={key++} className="mb-3 text-[22px] font-medium leading-none tracking-tight">
          {inline(trimmed.slice(2))}
        </h2>,
      )
    } else {
      blocks.push(
        <p key={key++} className="mb-3">
          {inline(trimmed)}
        </p>,
      )
    }
  }
  flushBullets()
  return <Fragment>{blocks}</Fragment>
}

function inline(text: string) {
  const nodes: ReactNode[] = []
  const pattern = /(\*\*[^*]+\*\*|\*[^*]+\*)/g
  let last = 0
  let match: RegExpExecArray | null
  let key = 0
  while ((match = pattern.exec(text))) {
    if (match.index > last) nodes.push(text.slice(last, match.index))
    const token = match[0]
    if (token.startsWith('**')) nodes.push(<strong key={key++}>{token.slice(2, -2)}</strong>)
    else nodes.push(<em key={key++}>{token.slice(1, -1)}</em>)
    last = match.index + token.length
  }
  if (last < text.length) nodes.push(text.slice(last))
  return nodes
}

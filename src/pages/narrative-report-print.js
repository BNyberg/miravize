export function ReportMarkdown({ markdown }) {
    const lines = markdown.replace(/\r\n/g, '\n').split('\n');
    const blocks = [];
    let bullets = [];
    let key = 0;
    function flushBullets() {
        if (bullets.length === 0)
            return;
        const items = bullets;
        bullets = [];
        blocks.push(_jsx("ul", { className: "mb-4 list-disc space-y-1 pl-5", children: items.map((item) => (_jsx("li", { children: inline(item) }, key++))) }, key++));
    }
    for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed) {
            flushBullets();
            continue;
        }
        if (trimmed.startsWith('- ')) {
            bullets.push(trimmed.slice(2));
            continue;
        }
        flushBullets();
        if (trimmed.startsWith('### ')) {
            blocks.push(_jsx("h3", { className: "mb-2 mt-5 text-[18px] font-medium leading-6", children: inline(trimmed.slice(4)) }, key++));
        }
        else if (trimmed.startsWith('# ')) {
            blocks.push(_jsx("h2", { className: "mb-3 text-[22px] font-medium leading-none tracking-tight", children: inline(trimmed.slice(2)) }, key++));
        }
        else {
            blocks.push(_jsx("p", { className: "mb-3", children: inline(trimmed) }, key++));
        }
    }
    flushBullets();
    return _jsx(Fragment, { children: blocks });
}
function inline(text) {
    const nodes = [];
    const pattern = /(\*\*[^*]+\*\*|\*[^*]+\*)/g;
    let last = 0;
    let match;
    let key = 0;
    while ((match = pattern.exec(text))) {
        if (match.index > last)
            nodes.push(text.slice(last, match.index));
        const token = match[0];
        if (token.startsWith('**'))
            nodes.push(_jsx("strong", { children: token.slice(2, -2) }, key++));
        else
            nodes.push(_jsx("em", { children: token.slice(1, -1) }, key++));
        last = match.index + token.length;
    }
    if (last < text.length)
        nodes.push(text.slice(last));
    return nodes;
}
